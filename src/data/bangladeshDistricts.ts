/**
 * Helper to get district by ID or case-insensitive name
 */
export function getBangladeshDistrict(nameOrId: string): BangladeshDistrictData | undefined {
  if (!nameOrId) return undefined;
  const key = nameOrId.toLowerCase().replace(/[^a-z]/g, '');
  if (BANGLADESH_DISTRICTS[key]) return BANGLADESH_DISTRICTS[key];

  // Try matching against name
  return Object.values(BANGLADESH_DISTRICTS).find(
    (d) =>
      d.name.toLowerCase() === nameOrId.toLowerCase() ||
      d.id === nameOrId.toLowerCase() ||
      d.bengaliName === nameOrId
  );
}

/**
 * Returns all 64 districts sorted alphabetically
 */
export function getAllBangladeshDistricts(): BangladeshDistrictData[] {
  return Object.values(BANGLADESH_DISTRICTS).sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * Returns districts grouped by division
 */
export function getDistrictsByDivision(): Record<string, BangladeshDistrictData[]> {
  const grouped: Record<string, BangladeshDistrictData[]> = {
    Dhaka: [],
    Chattogram: [],
    Sylhet: [],
    Rajshahi: [],
    Rangpur: [],
    Khulna: [],
    Barishal: [],
    Mymensingh: [],
  };

  for (const d of Object.values(BANGLADESH_DISTRICTS)) {
    if (grouped[d.division]) {
      grouped[d.division].push(d);
    }
  }

  // Sort each division's districts
  for (const div of Object.keys(grouped)) {
    grouped[div].sort((a, b) => a.name.localeCompare(b.name));
  }

  return grouped;
}
